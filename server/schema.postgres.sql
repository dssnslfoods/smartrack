-- ============================================================
-- เฟส 4: พื้นที่ราบ + พาเลท + เศษที่แกะจากลัง
--
-- เดิมทุกตำแหน่งต้องอยู่บนชั้นวาง (locations.rag_id NOT NULL) แต่ของจริง
-- มีทั้งวางบนพื้นราบและของที่แกะลังแล้วเหลือเป็นเศษ จึงขยายให้ครบทั้งสามแบบ:
--   RACK  = ตำแหน่งบนชั้นวาง (เหมือนเดิม)
--   FLOOR = พื้นที่ราบ วางพาเลทบนพื้น
--   BREAK = พื้นที่พิเศษสำหรับของที่แกะออกจากลังแล้ว (เศษไม่ครบลัง)
-- ============================================================

ALTER TABLE zones ADD COLUMN IF NOT EXISTS zone_type TEXT NOT NULL DEFAULT 'RACK'
  CHECK (zone_type IN ('RACK','FLOOR','BREAK'));

-- ตำแหน่งบนพื้นราบไม่มีชั้นวาง จึงต้องผูกโซนตรง ๆ และให้ rag_id ว่างได้
ALTER TABLE locations ALTER COLUMN rag_id DROP NOT NULL;
ALTER TABLE locations ADD COLUMN IF NOT EXISTS zone_id INTEGER REFERENCES zones(zone_id);
ALTER TABLE locations ADD COLUMN IF NOT EXISTS slot_no INTEGER;   -- ช่องที่เท่าไรในโซนพื้นราบ

-- ตำแหน่งเดิมทั้งหมดอยู่บนชั้นวาง — เติมโซนย้อนหลังจากชั้นวางที่สังกัด
UPDATE locations l SET zone_id = r.zone_id
  FROM rags r WHERE r.rag_id = l.rag_id AND l.zone_id IS NULL;

-- 1 SKU บรรจุได้กี่ลังต่อ 1 พาเลท — ใช้ตอนรับเข้าเพื่อคำนวณว่าต้องใช้กี่พาเลท
ALTER TABLE skus ADD COLUMN IF NOT EXISTS cartons_per_pallet INTEGER CHECK (cartons_per_pallet > 0);

-- ---------- พาเลท ----------
-- 1 พาเลท = สินค้า 1 SKU + 1 Lot เท่านั้น (ห้ามคละ) สร้างตอนรับเข้า
CREATE TABLE IF NOT EXISTS pallets (
  pallet_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pallet_no  TEXT NOT NULL UNIQUE,               -- เช่น PL-6909-0001
  sku_id     INTEGER NOT NULL REFERENCES skus(sku_id),
  lot_no     TEXT,
  mfg_date   DATE,
  exp_date   DATE,
  doc_id     INTEGER REFERENCES documents(doc_id),  -- ใบรับเข้าที่สร้างพาเลทนี้
  note       TEXT,
  status     TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','EMPTY')),
  created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Bangkok')
);

-- ของที่จัดเก็บผูกกับพาเลทได้ และบอกได้ว่าเป็นเศษที่แกะจากลังแล้วหรือไม่
ALTER TABLE stock_items ADD COLUMN IF NOT EXISTS pallet_id INTEGER REFERENCES pallets(pallet_id);
ALTER TABLE stock_items ADD COLUMN IF NOT EXISTS is_loose BOOLEAN NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_pallet_sku  ON pallets(sku_id, lot_no);
CREATE INDEX IF NOT EXISTS idx_loc_zone    ON locations(zone_id);
CREATE INDEX IF NOT EXISTS idx_item_pallet ON stock_items(pallet_id);

-- ---------- v_stock ใหม่ — รองรับทั้งชั้นวางและพื้นราบ ----------
-- ต้อง LEFT JOIN rags เพราะตำแหน่งพื้นราบไม่มีชั้นวาง และเอาโซนจาก locations ตรง ๆ
DROP VIEW IF EXISTS v_stock;
CREATE VIEW v_stock AS
SELECT i.item_id, i.lot_no, i.exp_date, i.quantity, i.note, i.stored_at,
       i.pallet_id, i.is_loose, p.pallet_no,
       s.sku_id, s.sku_code, s.sku_name, s.category, s.unit,
       l.location_id, l.location_code, l.level, l.depth, l.slot_no,
       r.rag_id, r.rag_no, z.zone_id, z.zone_code, z.zone_name, z.zone_type,
       w.warehouse_id, w.wh_code, w.wh_name,
       CASE WHEN i.exp_date IS NULL THEN NULL
            ELSE (i.exp_date - (now() AT TIME ZONE 'Asia/Bangkok')::date) END AS days_to_expiry,
       i.mfg_date, s.product_type, s.shelf_life_months, s.cartons_per_pallet,
       CASE WHEN i.exp_date IS NULL THEN NULL
            WHEN i.mfg_date IS NOT NULL AND i.exp_date > i.mfg_date THEN
              ROUND(100.0 * (i.exp_date - (now() AT TIME ZONE 'Asia/Bangkok')::date) / (i.exp_date - i.mfg_date))
            WHEN s.shelf_life_months IS NOT NULL THEN
              ROUND(100.0 * (i.exp_date - (now() AT TIME ZONE 'Asia/Bangkok')::date) / (s.shelf_life_months * 30.44))
            ELSE NULL END AS pct_remaining
FROM stock_items i
JOIN skus s      ON s.sku_id = i.sku_id
JOIN locations l ON l.location_id = i.location_id
JOIN zones z     ON z.zone_id = l.zone_id
LEFT JOIN rags r ON r.rag_id = l.rag_id
LEFT JOIN pallets p ON p.pallet_id = i.pallet_id
LEFT JOIN warehouses w ON w.warehouse_id = z.warehouse_id
WHERE i.status = 'IN_STOCK';

ALTER TABLE pallets ENABLE ROW LEVEL SECURITY;
