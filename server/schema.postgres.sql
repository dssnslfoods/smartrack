-- ---------- เฟส 1: โครงสร้างข้อมูล ----------
-- ประเภทสินค้า (RM/PM/SEMI/FG/POSM) + อายุสินค้า (เดือน) + วันผลิตของแต่ละ Lot
ALTER TABLE skus ADD COLUMN IF NOT EXISTS product_type TEXT
  CHECK (product_type IN ('RM','PM','SEMI','FG','POSM'));
ALTER TABLE skus ADD COLUMN IF NOT EXISTS shelf_life_months INTEGER CHECK (shelf_life_months > 0);
ALTER TABLE stock_items ADD COLUMN IF NOT EXISTS mfg_date DATE;

-- ต้นทุนต่อหน่วย — ใช้ตีมูลค่าสต๊อกและมูลค่าความเสี่ยงของหมดอายุเป็นเงินบาท
-- เว้นว่างได้ ระบบจะรายงานเป็นจำนวนหน่วยแทน
ALTER TABLE skus ADD COLUMN IF NOT EXISTS unit_cost NUMERIC(12,2) CHECK (unit_cost >= 0);

-- หน่วยนับเพิ่มเติมต่อสินค้า (หน่วยฐานคือ skus.unit) เช่น 1 ลัง = 12 ชิ้น
CREATE TABLE IF NOT EXISTS sku_units (
  sku_unit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku_id      INTEGER NOT NULL REFERENCES skus(sku_id) ON DELETE CASCADE,
  unit_name   TEXT NOT NULL,
  factor      NUMERIC NOT NULL CHECK (factor > 0),   -- 1 หน่วยนี้ = กี่หน่วยฐาน
  UNIQUE (sku_id, unit_name)
);

-- ---------- เฟส 2: ช่องทางขาย + กฎอายุคงเหลือ ----------
CREATE TABLE IF NOT EXISTS channels (
  channel_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_code      TEXT NOT NULL UNIQUE,
  channel_name      TEXT NOT NULL,
  min_pct_remaining INTEGER CHECK (min_pct_remaining BETWEEN 0 AND 100),  -- NULL = ไม่จำกัด
  status            TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE'))
);

-- ค่าตั้งระบบ (threshold ต่าง ๆ แก้ได้จากหน้าตั้งค่า)
CREATE TABLE IF NOT EXISTS app_settings (
  key   TEXT PRIMARY KEY,
  value TEXT
);
INSERT INTO app_settings (key, value) VALUES
  ('expiry_move_months', '12'),    -- อายุต่ำกว่านี้ (เดือน) → แนะนำย้ายเข้าโซน/คลัง PROM
  ('expiry_cutoff_months', '4')    -- อายุต่ำกว่านี้ (เดือน) → แนะนำตัดออกจากระบบ
ON CONFLICT (key) DO NOTHING;

INSERT INTO channels (channel_code, channel_name, min_pct_remaining)
SELECT * FROM (VALUES
  ('MT', 'Modern Trade', 80),
  ('GT', 'General Trade', 50)
) AS v(code, name, pct)
WHERE NOT EXISTS (SELECT 1 FROM channels);

-- ---------- เฟส 3+4: เอกสารคลัง (รับเข้า/จ่ายออก/โอน/คืน/ตัดเสีย/ปรับยอด) ----------
CREATE TABLE IF NOT EXISTS documents (
  doc_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_type     TEXT NOT NULL CHECK (doc_type IN ('GRN','ISSUE','TRANSFER','RETURN_IN','RETURN_OUT','SCRAP','ADJUST')),
  doc_no       TEXT NOT NULL UNIQUE,
  ref_no       TEXT,       -- เลข PO / SO / MO อ้างอิง (จาก Express/Odoo)
  party        TEXT,       -- ชื่อ Supplier / ลูกค้า
  channel_id   INTEGER REFERENCES channels(channel_id),
  reason       TEXT,       -- เหตุผล (รับคืน/ตัดเสีย)
  qc_status    TEXT CHECK (qc_status IN ('PASS','FAIL','QUARANTINE')),
  qc_note      TEXT,
  note         TEXT,
  status       TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CANCELLED')),
  -- pipeline จ่ายออก (เฉพาะ doc_type = 'ISSUE'): Picked → Packed → Shipped → Delivered
  ship_status  TEXT CHECK (ship_status IN ('PICKED','PACKED','SHIPPED','DELIVERED')),
  tracking_no  TEXT,
  carrier      TEXT,
  picked_at    TIMESTAMP,
  packed_at    TIMESTAMP,
  shipped_at   TIMESTAMP,
  delivered_at TIMESTAMP,
  created_by   INTEGER REFERENCES users(user_id),
  created_at   TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Bangkok')
);
ALTER TABLE movements ADD COLUMN IF NOT EXISTS doc_id INTEGER REFERENCES documents(doc_id);

-- ---------- เฟส 5: รอบนับสต็อก (Cycle Count) ----------
CREATE TABLE IF NOT EXISTS count_rounds (
  round_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_no     TEXT NOT NULL UNIQUE,
  warehouse_id INTEGER REFERENCES warehouses(warehouse_id),
  zone_id      INTEGER REFERENCES zones(zone_id),
  note         TEXT,
  status       TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','APPROVED','CANCELLED')),
  created_by   INTEGER REFERENCES users(user_id),
  created_at   TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Bangkok'),
  approved_by  INTEGER REFERENCES users(user_id),
  approved_at  TIMESTAMP
);

CREATE TABLE IF NOT EXISTS count_lines (
  line_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id     INTEGER NOT NULL REFERENCES count_rounds(round_id) ON DELETE CASCADE,
  location_id  INTEGER NOT NULL REFERENCES locations(location_id),
  item_id      INTEGER REFERENCES stock_items(item_id),
  sku_id       INTEGER REFERENCES skus(sku_id),
  lot_no       TEXT,
  expected_qty INTEGER NOT NULL DEFAULT 0,
  counted_qty  INTEGER,      -- NULL = ยังไม่ได้นับ
  note         TEXT,
  UNIQUE (round_id, location_id)
);

